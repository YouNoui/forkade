"""Publish the authored index tokens/kit to other pages. Never edit ui.css by hand."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def shared_css():
    source = (ROOT / 'web/index.html').read_text(encoding='utf-8')
    tokens = re.search(r':root\{([\s\S]*?)\n  \}', source)[0]
    kit = re.search(r'<style id="ui-kit">([\s\S]*?)</style>', source)[1]
    return '/* Generated by tools/build_ui.py from web/index.html. */\n' + tokens + '\n' + kit

def inline_ui(doc):
    return doc.replace('</head>', '<style data-shared-ui>\n' + shared_css() + '\n</style></head>', 1)

if __name__ == '__main__':
    (ROOT / 'web/ui.css').write_text(shared_css(), encoding='utf-8')
    print('Built shared UI tokens and kit from index.html')
