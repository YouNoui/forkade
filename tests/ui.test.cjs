const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n');
test('standalone and embedded UI kits match the authored index source',()=>{
 const index=read('web/index.html');
 const tokens=index.match(/:root\{([\s\S]*?)\n  \}/)[0];
 const kit=index.match(/<style id="ui-kit">([\s\S]*?)<\/style>/)[1];
 const css='/* Generated by tools/build_ui.py from web/index.html. */\n'+tokens+'\n'+kit;
 assert.equal(read('web/ui.css'),css);
 for(const id of ['echo3d','rampage','rumble'])assert.ok(read('web/games3d/'+id+'.html').includes(css),id+' contains current offline kit');
 for(const page of ['fair','admin','playground','terms','privacy','guidelines','delete'])assert.match(read('web/'+page+'.html'),/rel="stylesheet" href="\/ui.css"/);
});
